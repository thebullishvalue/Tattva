"""
Tattva — the README's edge table, rendered from the committed pooled-prior study.
तत्त्व (Tattva) — "Principle / Essence"

    python -m studies.render_docs_table                               # print it
    python -m studies.render_docs_table --write README.md             # refresh the README's block

Every measured number the README states about the catalogue is read here,
from the study's output (``data/priors/pooled_priors_h{h}_L{L}.json``), never
typed: :func:`render_edge_table` turns the file into one markdown block —

  * the study's provenance (run date, code, members, held-out set, failures);
  * each asset class's pooled grade of the claim, the two sizers and the call
    at the last vintage (μ ± se_μ, τ, k), and the pool a member reads;
  * the prior a member of each class actually reads for the claim — its
    leave-one-out entry — as the t that prior gives on its own;
  * the measured gap-closure split per class (arm G);
  * decisions A, B and C, and the R4 / R6 abort checks.

The README carries the block between :data:`BEGIN` and :data:`END`, and
``tests/test_docs.py`` holds it byte-identical to this function's output on
the committed file, so the table cannot drift from the study it reports.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from core.instruments import asset_class_name
from core.knobs import PRIORS_DIR, knob, priors_file_name

#: The markers the README's generated block sits between.
BEGIN = "<!-- edge-table:begin (generated by studies/render_docs_table.py; do not edit) -->"
END = "<!-- edge-table:end -->"

#: The study's objects, in the order the table shows them.
_OBJECTS = (("claim", "Claim"), ("sizer:swayam", "Swayam sizer"),
            ("sizer:reversion", "Reversion sizer"), ("call", "Call"))


def _num(x) -> float | None:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) else None


def _signed(x, nd: int = 3) -> str:
    """A signed number with a true minus sign, or '—'."""
    v = _num(x)
    return "—" if v is None else f"{v:+.{nd}f}".replace("-", "−")


def _plain(x, nd: int = 3) -> str:
    v = _num(x)
    return "—" if v is None else f"{v:.{nd}f}"


def _grade_cell(row: dict | None) -> str:
    """One class summary: 'μ ± se_μ · τ … · k …', or that nothing was graded."""
    if not row or _num(row.get("mu")) is None:
        return "not graded"
    return (f"{_signed(row['mu'])} ± {_plain(row.get('se_mu'))} · τ {_plain(row.get('tau'))} · "
            f"k {int(row.get('k') or 0)}")


def _prior_t(entry: dict) -> float | None:
    """The t a prior gives on its own: μ / max(√(τ² + var_μ), se_floor)."""
    mu, tau2, var, floor = (_num(entry.get(f)) for f in ("mu", "tau2", "var_mu", "se_floor"))
    if None in (mu, tau2, var, floor):
        return None
    sd = max(math.sqrt(tau2 + var), floor)
    return mu / sd if sd > 0 else None


def _table(header: tuple[str, ...], rows: list[tuple[str, ...]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|",
            *("| " + " | ".join(r) + " |" for r in rows)]


def render_edge_table(priors_json_path: str) -> str:
    """The README's edge table: the committed study's results as one markdown block.

    ``priors_json_path`` is a pooled-prior study output file. Classes are
    named as the pages name them (``core.instruments.asset_class_name``) and
    listed in the order the study lists them; every number is read from the
    file. The block ends with a newline.
    """
    data = json.loads(Path(priors_json_path).read_text(encoding="utf-8"))
    summary, priors = data.get("summary") or {}, data.get("priors") or {}
    classes = data.get("classes") or {}
    last = (data.get("vintages") or [None])[-1]
    held = data.get("held_out") or {}
    t0 = knob("STRENGTH_T0")
    out: list[str] = []

    failures = data.get("failures") or {}
    out.append(
        f"Study `{data.get('study')}` run {data.get('run_date')} on code "
        f"`{str(data.get('git_sha') or '')[:7]}` (script SHA-256 "
        f"`{str(data.get('script_sha256') or '')[:12]}…`), h = {data.get('h')}, "
        f"L = {data.get('exec_lag')}: {len(data.get('members') or [])} members, "
        f"{len(held.get('members') or [])} held out for the decisions"
        + (f"; not run: {', '.join(sorted(failures))}" if failures else "") + ".")
    out.append("")

    # ── Each class's pooled grades at the last vintage ──────────────────
    out.append(f"**Pooled grade by class** at the last vintage ({last}): the class's own "
               f"graded members pooled, μ ± se_μ, the catalogue-wide τ and the members k.")
    out.append("")
    rows = []
    for cls, members in classes.items():
        by_obj = summary.get(cls) or {}
        asof = sorted({str(r.get("asof")) for r in by_obj.values() if r.get("asof")})
        rows.append((asset_class_name(cls), str(len(members)),
                     *(_grade_cell(by_obj.get(obj)) for obj, _ in _OBJECTS),
                     ", ".join(asof) or "—"))
    out += _table(("Class", "Members", *(name for _, name in _OBJECTS), "Vintage"), rows)
    out.append("")
    if not any("call" in (summary.get(cls) or {}) for cls in classes):
        status = ((data.get("checks") or {}).get("R6") or {}).get("call", {}).get("status")
        out.append(f"No class has a pooled call grade{f': {status}' if status else ''}.")
        out.append("")

    # ── The claim prior a member actually reads ─────────────────────────
    out.append(f"**The claim prior each member reads** at {last}: its leave-one-out entry, "
               f"and the t that prior gives on its own, μ / max(√(τ² + var_μ), se_floor). "
               f"Trust opens at a posterior t of {t0:g}.")
    out.append("")
    rows, every = [], []
    claim = priors.get("claim") or {}
    for cls, members in classes.items():
        entries = [(m, (claim.get(m) or {}).get(last)) for m in members]
        entries = [(m, e) for m, e in entries if e]
        if not entries:
            rows.append((asset_class_name(cls), "—", "—", "—", "—"))
            continue
        ts = [(t, m) for m, e in entries if (t := _prior_t(e)) is not None]
        every += ts
        mus = [e["mu"] for _, e in entries]
        scopes = sorted({str(e["scope"]) for _, e in entries})
        lo, hi = min(ts), max(ts)
        rows.append((asset_class_name(cls), ", ".join(scopes),
                     f"{_signed(min(mus))} … {_signed(max(mus))}",
                     f"{_signed(lo[0], 2)} … {_signed(hi[0], 2)}", hi[1]))
    out += _table(("Class", "Scope", "Prior μ", "t of the prior alone", "Highest t"), rows)
    out.append("")
    if every:
        lo, hi = min(every), max(every)
        opens = [m for t, m in every if t >= t0]
        out.append(
            (f"{len(opens)} of {len(every)} members' claim priors reach t {t0:g} on their own "
             f"({', '.join(opens)})" if opens
             else f"No member's claim prior reaches t {t0:g} on its own")
            + f": they run from {_signed(lo[0], 2)} ({lo[1]}) to {_signed(hi[0], 2)} ({hi[1]}).")
        out.append("")
        for cls, members in classes.items():
            row = (summary.get(cls) or {}).get("claim") or {}
            mu, se = _num(row.get("mu")), _num(row.get("se_mu"))
            scopes = {str(((claim.get(m) or {}).get(last) or {}).get("scope")) for m in members}
            if mu is not None and se and mu / se >= t0 and not any(x.startswith("class") for x in scopes):
                out.append(
                    f"The {asset_class_name(cls)} class's own claim summary, {_signed(mu)} ± "
                    f"{_plain(se)} on k {int(row.get('k') or 0)} ({', '.join(members)}), is "
                    f"{mu / se:.2f} standard errors from zero, but with fewer than "
                    f"{knob('POOL_MIN_MEMBERS')} other members no member reads it: each reads "
                    f"the {', '.join(sorted(scopes))} pool.")
                out.append("")

    # ── Who closes the gap (arm G) ──────────────────────────────────────
    g = ((data.get("arms") or {}).get("G") or {}).get("per_class") or {}
    h = data.get("h")
    out.append(f"**Who closes the gap** (arm G): over {h} sessions, the share of the open gap "
               f"that price closed, and the slopes of the {h}-session change in log fair value "
               f"and in log price on the gap — the mean over a class's members, with the SD "
               f"across them.")
    out.append("")
    rows = []
    for cls in classes:
        r = g.get(cls)
        if not r:
            continue
        ps, bfv, bp = r.get("price_share") or {}, r.get("b_fv") or {}, r.get("b_price") or {}
        share = _num(ps.get("mean"))
        rows.append((asset_class_name(cls), str(int(r.get("k") or 0)),
                     (f"{_signed(share * 100, 1)}% (SD {_plain(_num(ps.get('sd')) * 100, 1)}%)"
                      if share is not None and _num(ps.get("sd")) is not None else "—"),
                     f"{_signed(bfv.get('mean'))} (SD {_plain(bfv.get('sd'))})",
                     f"{_signed(bp.get('mean'))} (SD {_plain(bp.get('sd'))})"))
    out += _table(("Class", "k", "Price's share of the closing", "Fair value's slope on the gap",
                   "Price's slope on the gap"), rows)
    out.append("")
    shares = [(_num((g[c].get("price_share") or {}).get("mean")), c) for c in classes if c in g]
    shares = [(v, c) for v, c in shares if v is not None]
    if shares:
        lo, hi = min(shares), max(shares)
        out.append(f"Class by class, price did between {_signed(lo[0] * 100, 1)}% "
                   f"({asset_class_name(lo[1])}) and {_signed(hi[0] * 100, 1)}% "
                   f"({asset_class_name(hi[1])}) of the closing; fair value moving toward price "
                   f"did the rest.")
        out.append("")

    # ── Decisions and checks ────────────────────────────────────────────
    dec = data.get("decisions") or {}
    a, b, c = dec.get("A") or {}, dec.get("B") or {}, dec.get("C") or {}
    da, db, dc = a.get("b_delta_ic") or {}, b.get("delta_ic") or {}, b.get("call_vs_bare_claim") or {}
    terc = c.get("terciles") or {}
    out.append("**Decisions**, on the held-out members only:")
    out.append("")
    out += _table(("Decision", "Value", "Measured"), [
        ("A · claim centring (recorded, never applied)", f"`{a.get('value')}`",
         f"raw FVO fails the C12 unit contract on {len(a.get('raw_fails') or [])}; the candidate "
         f"`{a.get('candidate')}` passes on {len(a.get('candidate_passes') or [])} of them "
         f"(adoption needs 2/3); paired ΔIC {_signed(da.get('delta'))} ± {_plain(da.get('se'))}"),
        ("B · SIZERS_ENABLED", f"`{b.get('value')}`",
         f"ΔIC(d·∏factor − d) {_signed(db.get('delta'))} ± {_plain(db.get('se'))} on "
         f"{int(db.get('n_members') or 0)} members (released iff ≥ −1 SE); call vs bare claim "
         f"{_signed(dc.get('delta'))} ± {_plain(dc.get('se'))} on {int(dc.get('n_members') or 0)} "
         f"member (information only)"),
        ("C · TIER_RULE", f"`{c.get('value')}`",
         f"{int(c.get('members_with_issued_calls') or 0)} held-out member issued calls; n/h per "
         f"tercile " + " / ".join(str(int((terc.get(k) or {}).get('n_win') or 0))
                                  for k in ("T1", "T2", "T3"))
         + f" (needs {knob('TIER_MIN_WIN')} each)"),
    ])
    out.append("")
    checks = data.get("checks") or {}
    r4 = checks.get("R4") or {}
    r6 = checks.get("R6") or {}
    graded = [obj for obj, _ in _OBJECTS if _num((r4.get(obj) or {}).get("median")) is not None]
    out.append(
        "Checks: R4, the FFT shift-null SE against a brute-force null (median ratio, band "
        + " – ".join(f"{x:g}" for x in ((r4.get("claim") or {}).get("band") or []))
        + "): " + ", ".join(f"{obj} {_plain(r4[obj]['median'])}" for obj in graded)
        + f" — {'pass' if all(r.get('pass') for r in r4.values()) else 'FAIL'}; R6, the "
        f"bootstrap pool variance against the closed form (median ratio, bar "
        f"{_plain((r6.get('claim') or {}).get('max_ratio'), 1)}): "
        + ", ".join(f"{obj} {_plain(r6[obj]['median'], 2)}" for obj in graded if obj in r6)
        + f" — {'pass' if all(r.get('pass') for r in r6.values()) else 'FAIL'}.")
    return "\n".join(out) + "\n"


def committed_path() -> Path:
    """The committed study output for the app's h and L."""
    from core.config import FORECAST_HORIZON
    return PRIORS_DIR / priors_file_name(FORECAST_HORIZON, knob("EXECUTION_LAG"))


def readme_block(text: str) -> str:
    """The generated block a document carries between BEGIN and END (exclusive)."""
    start, end = text.index(BEGIN) + len(BEGIN) + 1, text.index(END)
    return text[start:end]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--priors", default=None, help="the study output (default: the committed one)")
    ap.add_argument("--write", default=None, metavar="DOC",
                    help="replace the block between the markers in DOC instead of printing")
    args = ap.parse_args(argv)
    table = render_edge_table(str(args.priors or committed_path()))
    if not args.write:
        print(table, end="")
        return 0
    doc = Path(args.write)
    text = doc.read_text(encoding="utf-8")
    old = readme_block(text)
    doc.write_text(text.replace(BEGIN + "\n" + old, BEGIN + "\n" + table, 1), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
